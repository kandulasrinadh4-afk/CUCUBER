// Helper functions for easy consumption across components
export const ALL_BATTING_LESSONS: MasterclassLesson[] = BATTING_MODULES.flatMap((m) => m.lessons);
export const ALL_BOWLING_LESSONS: MasterclassLesson[] = BOWLING_MODULES.flatMap((m) => m.lessons);
export const ALL_MASTERCLASS_LESSONS: MasterclassLesson[] = [
  ...ALL_BATTING_LESSONS,
  ...ALL_BOWLING_LESSONS,
];

export const TOTAL_BATTING_LESSONS = ALL_BATTING_LESSONS.length; // 37
export const TOTAL_BOWLING_LESSONS = ALL_BOWLING_LESSONS.length; // 30
export const TOTAL_MASTERCLASS_LESSONS = ALL_MASTERCLASS_LESSONS.length; // 67

export function getLessonById(id: string): MasterclassLesson | undefined {
  return ALL_MASTERCLASS_LESSONS.find((l) => l.id === id);
}

export function getNextLesson(currentLessonId: string): MasterclassLesson | null {
  const currentIndex = ALL_MASTERCLASS_LESSONS.findIndex((l) => l.id === currentLessonId);
  if (currentIndex === -1 || currentIndex === ALL_MASTERCLASS_LESSONS.length - 1) {
    return null;
  }
  return ALL_MASTERCLASS_LESSONS[currentIndex + 1];
}

export function getRecommendedLessons(completedIds: string[], limit: number = 3): MasterclassLesson[] {
  const completedSet = new Set(completedIds);
  const uncompleted = ALL_MASTERCLASS_LESSONS.filter((l) => !completedSet.has(l.id));

  if (uncompleted.length === 0) {
    return ALL_MASTERCLASS_LESSONS.slice(0, limit);
  }

  // Smart recommendation: pick next foundational lesson from batting and bowling
  const recBatting = uncompleted.find((l) => l.discipline === 'batting');
  const recBowling = uncompleted.find((l) => l.discipline === 'bowling');

  const recs: MasterclassLesson[] = [];
  if (recBatting) recs.push(recBatting);
  if (recBowling) recs.push(recBowling);

  for (const lesson of uncompleted) {
    if (recs.length >= limit) break;
    if (!recs.some((r) => r.id === lesson.id)) {
      recs.push(lesson);
    }
  }

  return recs.slice(0, limit);
}
